package com.allergytrack.app.domain.export

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.os.Environment
import com.allergytrack.app.domain.model.Correlation
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.*
import javax.inject.Inject

class MedicalReportExporter @Inject constructor(
    @ApplicationContext private val context: Context
) {
    suspend fun generatePdfReport(
        correlations: List<Correlation>,
        aiSummary: String
    ): File? = withContext(Dispatchers.IO) {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 size
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas
        val paint = Paint()

        var currentY = 50f
        val margin = 50f
        val pageWidth = 595f

        // Title
        paint.textSize = 24f
        paint.isFakeBoldText = true
        paint.color = Color.BLACK
        canvas.drawText("AllergyTrack Medical Report", margin, currentY, paint)
        currentY += 40f

        // Date
        paint.textSize = 12f
        paint.isFakeBoldText = false
        paint.color = Color.GRAY
        val date = SimpleDateFormat("MMMM dd, yyyy", Locale.getDefault()).format(Date())
        canvas.drawText("Generated on $date", margin, currentY, paint)
        currentY += 40f

        // AI Summary Section
        paint.color = Color.BLACK
        paint.isFakeBoldText = true
        paint.textSize = 16f
        canvas.drawText("Clinical Summary", margin, currentY, paint)
        currentY += 25f

        paint.isFakeBoldText = false
        paint.textSize = 12f
        val lines = wrapText(aiSummary, paint, pageWidth - 2 * margin)
        lines.forEach { line ->
            canvas.drawText(line, margin, currentY, paint)
            currentY += 20f
        }
        currentY += 20f

        // Top Triggers Section
        paint.isFakeBoldText = true
        paint.textSize = 16f
        canvas.drawText("Identified Potential Triggers", margin, currentY, paint)
        currentY += 30f

        correlations.take(5).forEach { correlation ->
            // Background box for each trigger
            val rectPaint = Paint()
            rectPaint.color = Color.rgb(240, 240, 240)
            canvas.drawRect(margin - 5, currentY - 15, pageWidth - margin + 5, currentY + 45, rectPaint)

            paint.isFakeBoldText = true
            paint.textSize = 14f
            paint.color = Color.BLACK
            canvas.drawText("${correlation.trigger}", margin + 10, currentY + 5, paint)
            
            paint.isFakeBoldText = false
            paint.textSize = 11f
            paint.color = Color.DKGRAY
            canvas.drawText(
                "Correlation: ${(correlation.score * 100).toInt()}% confidence | Symptom: ${correlation.symptomType.label}",
                margin + 10, currentY + 25, paint
            )
            
            currentY += 70f
        }

        // Footer
        paint.textSize = 10f
        paint.color = Color.LTGRAY
        canvas.drawText("This report is generated by AI based on user logs and is for informational purposes only.", margin, 810f, paint)

        pdfDocument.finishPage(page)

        val fileName = "AllergyReport_${System.currentTimeMillis()}.pdf"
        val file = File(context.getExternalFilesDir(Environment.DIRECTORY_DOCUMENTS), fileName)

        try {
            pdfDocument.writeTo(FileOutputStream(file))
            pdfDocument.close()
            file
        } catch (e: Exception) {
            e.printStackTrace()
            null
        }
    }

    private fun wrapText(text: String, paint: Paint, maxWidth: Float): List<String> {
        val words = text.split(" ")
        val lines = mutableListOf<String>()
        var currentLine = StringBuilder()

        for (word in words) {
            val testLine = if (currentLine.isEmpty()) word else "${currentLine} $word"
            if (paint.measureText(testLine) <= maxWidth) {
                currentLine.append(if (currentLine.isEmpty()) word else " $word")
            } else {
                lines.add(currentLine.toString())
                currentLine = StringBuilder(word)
            }
        }
        if (currentLine.isNotEmpty()) lines.add(currentLine.toString())
        return lines
    }
}
